/* ============================================================
   Thesis Collection — portal logic (vanilla)
   Renders cards from data/theses.json (generated by scripts/build.mjs),
   with client-side search + year/tag filtering.
   ============================================================ */

(() => {
  "use strict";

  /* ---------------------------------------------------------
     1. Data source — the generated, committed index.
     --------------------------------------------------------- */
  const loadData = () =>
    fetch("./data/theses.json").then((r) => {
      if (!r.ok) throw new Error(`theses.json HTTP ${r.status}`);
      return r.json();
    });

  /* ---------------------------------------------------------
     3. State
     --------------------------------------------------------- */
  const state = {
    items: [],
    q: "",
    year: null,    // number | null
    tag: null,     // string | null
  };

  const els = {
    grid:        document.getElementById("grid"),
    empty:       document.getElementById("empty"),
    q:           document.getElementById("q"),
    yearChips:   document.getElementById("year-chips"),
    tagChips:    document.getElementById("tag-chips"),
    stat:        document.getElementById("stat-line"),
    resultCount: document.getElementById("result-count"),
    clearBtn:    document.getElementById("clear-filters"),
    themeBtn:    document.getElementById("theme-toggle"),
  };

  /* ---------------------------------------------------------
     4. Utilities
     --------------------------------------------------------- */
  const esc = (s) =>
    String(s ?? "").replace(/[&<>"']/g, (c) =>
      ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c])
    );

  // Wrap any CJK runs in <span lang="zh"> so the CJK font kicks in cleanly.
  const tagCJK = (s) => {
    if (!s) return "";
    const escaped = esc(s);
    return escaped.replace(
      /([\u3000-\u303f\u3400-\u4dbf\u4e00-\u9fff\uf900-\ufaff\uff00-\uffef]+)/g,
      '<span lang="zh">$1</span>'
    );
  };

  const highlight = (s, q) => {
    if (!q) return tagCJK(s);
    // escape first, then highlight, then CJK-tag the unmatched parts.
    const safe = esc(s);
    const re = new RegExp(
      "(" + q.replace(/[.*+?^${}()|[\]\\]/g, "\\$&") + ")",
      "ig"
    );
    return safe
      .split(re)
      .map((part, i) =>
        i % 2 === 1
          ? `<mark class="hit">${part}</mark>`
          : part.replace(
              /([\u3000-\u303f\u3400-\u4dbf\u4e00-\u9fff\uf900-\ufaff\uff00-\uffef]+)/g,
              '<span lang="zh">$1</span>'
            )
      )
      .join("");
  };

  const debounce = (fn, ms = 120) => {
    let t;
    return (...a) => {
      clearTimeout(t);
      t = setTimeout(() => fn(...a), ms);
    };
  };

  /* ---------------------------------------------------------
     5. Filtering
     --------------------------------------------------------- */
  const matches = (item) => {
    if (state.year && item.year !== state.year) return false;
    if (state.tag && !(item.tags || []).includes(state.tag)) return false;
    if (state.q) {
      const hay = [
        item.title,
        item.subtitle,
        item.abstract,
        (item.authors || []).join(" "),
        item.advisor,
        (item.tags || []).join(" "),
        item.institution,
        item.slug,
      ]
        .filter(Boolean)
        .join(" ")
        .toLowerCase();
      if (!hay.includes(state.q.toLowerCase())) return false;
    }
    return true;
  };

  /* ---------------------------------------------------------
     6. Rendering
     --------------------------------------------------------- */

  const ICON_EXT = `<svg viewBox="0 0 24 24" width="13" height="13" aria-hidden="true">
    <path d="M7 17L17 7M9 7h8v8" fill="none" stroke="currentColor" stroke-width="1.8"
          stroke-linecap="round" stroke-linejoin="round"/>
  </svg>`;

  const ICON_REPO = `<svg viewBox="0 0 24 24" width="15" height="15" aria-hidden="true">
    <path fill="currentColor" d="M12 .5C5.65.5.5 5.65.5 12c0 5.08 3.29 9.39 7.86 10.91.58.11.79-.25.79-.56v-2c-3.2.7-3.87-1.37-3.87-1.37-.52-1.34-1.28-1.69-1.28-1.69-1.05-.71.08-.7.08-.7 1.16.08 1.77 1.19 1.77 1.19 1.03 1.77 2.7 1.26 3.36.96.1-.75.4-1.26.73-1.55-2.55-.29-5.24-1.28-5.24-5.7 0-1.26.45-2.28 1.18-3.09-.12-.29-.51-1.46.11-3.04 0 0 .97-.31 3.19 1.18a11 11 0 0 1 5.82 0c2.22-1.49 3.19-1.18 3.19-1.18.62 1.58.23 2.75.11 3.04.74.81 1.18 1.83 1.18 3.09 0 4.43-2.69 5.41-5.26 5.69.41.36.78 1.06.78 2.14v3.17c0 .31.21.68.79.56A11.51 11.51 0 0 0 23.5 12C23.5 5.65 18.35.5 12 .5Z"/>
  </svg>`;

  const ICON_ARCH = `<svg viewBox="0 0 24 24" width="15" height="15" aria-hidden="true" fill="none" stroke="currentColor" stroke-width="1.6" stroke-linecap="round" stroke-linejoin="round">
    <rect x="3" y="4" width="18" height="4" rx="1"/>
    <path d="M5 8v11a1 1 0 0 0 1 1h12a1 1 0 0 0 1-1V8"/>
    <line x1="10" y1="13" x2="14" y2="13"/>
  </svg>`;

  const renderCard = (t) => {
    const q = state.q.trim();

    const authors = (t.authors || []).length
      ? `<div><span class="label">By</span><span class="authors">${(t.authors || [])
          .map((a) => highlight(a, q))
          .join(", ")}</span></div>`
      : "";

    const advisor = t.advisor
      ? `<span class="advisor"><span class="label">Advisor</span>${highlight(t.advisor, q)}</span>`
      : "";

    const people = authors || advisor
      ? `<div class="card-people">${authors}${advisor}</div>`
      : "";

    const subtitle = t.subtitle
      ? `<p class="card-subtitle">${highlight(t.subtitle, q)}</p>`
      : "";

    const abstract = t.abstract
      ? `<p class="card-abstract">${highlight(t.abstract, q)}</p>`
      : "";

    const inst = t.institution
      ? `<p class="card-inst">${tagCJK(t.institution)}</p>`
      : "";

    const tags = (t.tags || []).length
      ? `<div class="card-tags">${(t.tags || [])
          .map((x) => `<span class="tag">${esc(x)}</span>`)
          .join("")}</div>`
      : "";

    const year = t.year
      ? `<span class="card-year">${esc(t.year)}</span>`
      : "";

    const slug = t.slug
      ? `<span class="card-slug" title="${esc(t.slug)}">${esc(t.slug)}</span>`
      : "";

    const archiveBadge = t.archive
      ? `<span class="badge badge-archive" title="Archived copy lives in this repo">Archived</span>`
      : "";

    // Aux links (small, secondary). Stop event bubbling so they don't trigger the card-wide nav.
    const auxParts = [];
    if (t.repo) {
      auxParts.push(
        `<a class="aux-link" href="${esc(t.repo)}" target="_blank" rel="noopener"
            aria-label="Source repository" title="Repository"
            onclick="event.stopPropagation()">${ICON_REPO}</a>`
      );
    }
    if (t.archiveUrl) {
      auxParts.push(
        `<a class="aux-link" href="${esc(t.archiveUrl)}" rel="noopener"
            aria-label="Archived copy" title="Archived copy"
            onclick="event.stopPropagation()">${ICON_ARCH}</a>`
      );
    }
    const aux = auxParts.length
      ? `<div class="card-aux">${auxParts.join("")}</div>`
      : "";

    const cta = `
      <span class="card-cta">
        Read thesis ${ICON_EXT}
      </span>
    `;

    // Card is an <article>. The title <a> uses a stretched ::after so the
    // whole card is clickable, but aux <a> elements (repo/archive) sit above
    // and remain independently clickable — no illegal nested anchors.
    return `
      <article class="card">
        <div class="card-top">
          <div class="card-top-left">
            ${year}
            ${slug}
          </div>
          ${archiveBadge}
        </div>
        <h2 class="card-title">
          <a class="card-link-stretch" href="${esc(t.url)}" target="_blank" rel="noopener"
             aria-label="${esc(t.title)} — opens thesis site in new tab">${highlight(t.title, q)}</a>
        </h2>
        ${subtitle}
        ${people}
        ${abstract}
        ${inst}
        ${tags}
        <div class="card-foot">
          ${cta}
          ${aux}
        </div>
      </article>
    `;
  };

  const renderGrid = () => {
    const matched = state.items.filter(matches);
    els.grid.removeAttribute("aria-busy");

    if (matched.length === 0) {
      els.grid.innerHTML = "";
      els.empty.hidden = false;
    } else {
      els.empty.hidden = true;
      els.grid.innerHTML = matched.map(renderCard).join("");
    }

    // Result count + clear-filters visibility
    const total = state.items.length;
    const filtered = state.q || state.year || state.tag;
    els.resultCount.textContent = filtered
      ? `${matched.length} of ${total} shown`
      : `${total} ${total === 1 ? "thesis" : "theses"}`;
    els.clearBtn.hidden = !filtered;
  };

  const renderChips = () => {
    // Years (desc) + tags (alpha), each with counts.
    const yearCounts = new Map();
    const tagCounts = new Map();
    state.items.forEach((t) => {
      if (t.year) yearCounts.set(t.year, (yearCounts.get(t.year) || 0) + 1);
      (t.tags || []).forEach((tag) =>
        tagCounts.set(tag, (tagCounts.get(tag) || 0) + 1)
      );
    });

    const years = [...yearCounts.keys()].sort((a, b) => b - a);
    els.yearChips.innerHTML = years
      .map(
        (y) => `
        <button class="chip" type="button" data-year="${y}"
                aria-pressed="${state.year === y}">
          ${y}<span class="chip-count">${yearCounts.get(y)}</span>
        </button>`
      )
      .join("");

    const tags = [...tagCounts.entries()].sort((a, b) => {
      // sort by count desc, then alpha
      if (b[1] !== a[1]) return b[1] - a[1];
      return a[0].localeCompare(b[0]);
    });
    els.tagChips.innerHTML = tags
      .map(
        ([tag, n]) => `
        <button class="chip" type="button" data-tag="${esc(tag)}"
                aria-pressed="${state.tag === tag}">
          ${esc(tag)}<span class="chip-count">${n}</span>
        </button>`
      )
      .join("");
  };

  const renderStat = () => {
    const n = state.items.length;
    const years = state.items.map((t) => t.year).filter(Boolean);
    const lo = Math.min(...years), hi = Math.max(...years);
    const range = years.length
      ? lo === hi ? `${lo}` : `${lo}–${hi}`
      : "—";
    els.stat.innerHTML =
      `<strong>${n}</strong> ${n === 1 ? "thesis" : "theses"} · ${range}`;
  };

  /* ---------------------------------------------------------
     7. Events
     --------------------------------------------------------- */

  const onSearch = debounce((e) => {
    state.q = e.target.value || "";
    renderGrid();
  }, 80);

  const onChipClick = (e) => {
    const btn = e.target.closest(".chip");
    if (!btn) return;
    if (btn.dataset.year) {
      const y = Number(btn.dataset.year);
      state.year = state.year === y ? null : y;
    } else if (btn.dataset.tag) {
      const tg = btn.dataset.tag;
      state.tag = state.tag === tg ? null : tg;
    }
    renderChips();
    renderGrid();
  };

  const clearAll = () => {
    state.q = "";
    state.year = null;
    state.tag = null;
    els.q.value = "";
    renderChips();
    renderGrid();
  };

  // Theme toggle (overrides system preference, persists)
  const initTheme = () => {
    const saved = localStorage.getItem("portal-theme");
    if (saved === "light" || saved === "dark") {
      document.documentElement.setAttribute("data-theme", saved);
    }
  };
  const toggleTheme = () => {
    const cur = document.documentElement.getAttribute("data-theme");
    const prefersDark = matchMedia("(prefers-color-scheme: dark)").matches;
    const isDark = cur === "dark" || (!cur && prefersDark);
    const next = isDark ? "light" : "dark";
    document.documentElement.setAttribute("data-theme", next);
    localStorage.setItem("portal-theme", next);
  };

  /* ---------------------------------------------------------
     8. Bootstrap
     --------------------------------------------------------- */

  const init = async () => {
    initTheme();

    els.q.addEventListener("input", onSearch);
    els.yearChips.addEventListener("click", onChipClick);
    els.tagChips.addEventListener("click", onChipClick);
    els.clearBtn.addEventListener("click", clearAll);
    els.empty.addEventListener("click", (e) => {
      if (e.target.matches("[data-clear]")) clearAll();
    });
    els.themeBtn.addEventListener("click", toggleTheme);

    // "/" focuses search.
    document.addEventListener("keydown", (e) => {
      if (e.key === "/" && document.activeElement !== els.q) {
        e.preventDefault();
        els.q.focus();
      }
      if (e.key === "Escape" && document.activeElement === els.q) {
        els.q.blur();
      }
    });

    try {
      state.items = await loadData();
    } catch (err) {
      console.error("Failed to load theses:", err);
      state.items = [];
      els.grid.innerHTML =
        `<div class="empty" style="grid-column:1/-1;">
           <h2>Couldn't load the collection.</h2>
           <p>Check the network or your <code>data/theses.json</code> path.</p>
         </div>`;
      return;
    }

    renderStat();
    renderChips();
    renderGrid();
  };

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", init);
  } else {
    init();
  }
})();
